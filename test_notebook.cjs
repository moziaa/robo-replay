'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync(__dirname + '/notebook.html', 'utf8');
const source = html.split('// Comparison math')[1].split('// End comparison math.')[0];
const context = vm.createContext({});
vm.runInContext('// Comparison math' + source, context);
const summarize = data => JSON.parse(JSON.stringify(context.summarizeRuns(data)));
const run = (mission, variant, seconds, success) => ({mission, variant, seconds, success});
assert.deepEqual(summarize([]), []);
const data = [run('Cube', 'Scoop', 20, true), run('Cube', 'Scoop', 2, false), run('Cube', 'Scoop', 10, true), run('Cube', 'Scoop', 30, true)];
const original = JSON.stringify(data);
assert.deepEqual(summarize(data), [{mission:'Cube',variant:'Scoop',attempts:4,successes:3,median:15,successfulMedian:20}]);
assert.equal(JSON.stringify(data), original);
assert.deepEqual(summarize([run('Cube','Rails',4,false)])[0].successfulMedian, null);
assert.equal(summarize([run('A','B / C',1,true),run('A / B','C',2,true),run('Other','C',3,true)]).length,3);
assert.equal(summarize([run('__proto__','<b>literal</b>',86400,true)])[0].median,86400);
console.log('Browser comparison checks passed: medians, failures, mission separation, nonmutation, special names.');
